                    veertien (14) dagen na factuurdatum. Bij niet-tijdige betaling van de
                    factuur zal voor iedere 7 dagen dat er geen betaling is ontvangen een
                    strip van de strippenkaart worden afgetekend, als zijnde vergoeding
                    van de administratiekosten.
                </p>

                <p class="text-brown leading-relaxed mb-4">
                    <strong>7.3</strong>
                    Opdrachtnemer is verplicht een prijsopgave te overhandigen indien
                    gewenst door opdrachtgever.
                </p>

                <p class="text-brown leading-relaxed mb-4">
                    <strong>7.4</strong>
                    De tijdsduur van de eerste overeenkomst (4 keer) vormt een proefperiode
                    om te kijken of alles naar wens verloopt. Bij goed verloop wordt de
                    overeenkomst steeds stilzwijgend met 10 strippen verlengd.
                </p>

                <p class="text-brown leading-relaxed mb-4">
                    <strong>7.5</strong>
                    Opdrachtgever dient bij beëindiging van de overeenkomst een opzegtermijn
                    van vier weken in acht te nemen. Voor de niet-gebruikte strippen zal
                    geen restitutie plaatsvinden.
                </p>

                <p class="text-brown leading-relaxed mb-4">
                    <strong>7.6</strong>
                    Wanneer opdrachtgever langer dan vier weken achtereen geen gebruik
                    maakt van de door opdrachtnemer geleverde dienst, dan vervalt het recht
                    op de gereserveerde plaats op de afgesproken uitlaatdagen en is
                    opdrachtnemer gerechtigd deze plaats op te vullen. Voor de niet-gebruikte
                    strippen vindt geen restitutie plaats. Enkel op medische grond van de
                    gezondheid van de hond kan hiervan worden afgeweken, opdrachtgever dient
                    in dat geval een verklaring van een dierenarts te overleggen.
                </p>

                <p class="text-brown leading-relaxed">
                    <strong>7.7</strong>
                    Voor de 10 strippenkaart geldt de geldigheidsduur van 4 weken gerekend
                    vanaf de laatste afgetekende datum op de kaart. Wanneer geen (tijdige)
                    opzegging is ontvangen, ontvangt u voor het verstrijken van de
                    geldigheidsduur een nieuwe kaart en factuur. De niet-verbruikte strippen
                    op de oude kaart vervallen.
                </p>
            </section>


